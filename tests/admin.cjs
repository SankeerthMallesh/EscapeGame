// Admin panel: unlock with ADMIN, open with F8, every button does its job; online, non-hosts can't touch the island.
const { chromium } = require('playwright'); const path = require('path');
const { PeerServer } = require('peer');
const PORT = 9479, results = []; let fails = 0;
const check = (n, ok, x = '') => { results.push(`${ok ? 'PASS' : 'FAIL'}  ${n} ${x}`); if (!ok) fails++; };
(async () => {
  PeerServer({ port: PORT, path: '/', host: '127.0.0.1' }); await new Promise((r) => setTimeout(r, 400));
  const args = ['--enable-unsafe-swiftshader', '--use-angle=swiftshader', '--ignore-gpu-blocklist'];
  const url = 'file://' + path.resolve(__dirname, '..', 'escape-from-joury.html') + '?norender&peer=127.0.0.1:' + PORT;
  const open = async () => { const browser = await chromium.launch({ args }); const page = await browser.newPage({ viewport: { width: 1280, height: 760 } }); const logs = []; page.on('console', (m) => { if (m.type() === 'error') logs.push(m.text().slice(0, 300)); }); page.on('pageerror', (e) => logs.push('PAGEERROR ' + e.message + ' ' + (e.stack || '').slice(0, 300))); await page.goto(url); await page.waitForFunction(() => window.EFJ && EFJ.state === 'title', null, { timeout: 180000 }); return { browser, page, logs }; };
  const A = await open();
  const run = (code) => A.page.evaluate((c) => EFJ.run(c), code);
  const until = (expr, ms = 20000) => A.page.waitForFunction((e) => { try { return EFJ.run(e); } catch (x) { return false; } }, expr, { timeout: ms, polling: 100 }).then(() => true).catch(() => false);
  const click = (label) => A.page.click(`#adminBody .adm-btn:text-is("${label}")`);
  await A.page.click('#btnPlay'); await A.page.waitForTimeout(300); await A.page.click('#btnSkip'); await until("Game.state === 'play'");
  await A.page.keyboard.press('F8'); check('F8 does nothing without the code', !(await run('Admin.open')));
  await A.page.keyboard.press('Escape'); await until("Game.state === 'paused'"); await A.page.click('#btnQuit'); await until("Game.state === 'title'");
  await A.page.click('#btnCodes'); await A.page.fill('#redeemInput', 'admin'); await A.page.click('#btnRedeem');
  check('ADMIN code unlocks the panel', (await A.page.textContent('#redeemStatus')).includes('Admin panel'));
  await A.page.click('#btnPlay'); await A.page.waitForTimeout(300); await A.page.click('#btnSkip'); await until("Game.state === 'play'");
  await A.page.keyboard.press('F8');
  check('F8 opens the panel', (await run('Admin.open')) && (await A.page.isVisible('#adminBody')));
  await A.page.waitForTimeout(400);
  check('live info shows', (await A.page.textContent('#adminInfo')).includes('Joury'));
  await click('Dock & boat'); check('teleport to the dock', await until('World.onDock(Player.pos.x, Player.pos.z)'));
  await click('Graveyard'); check('teleport to a landmark', await until("Math.hypot(Player.pos.x + 58, Player.pos.z + 22) < 8"));
  await click('Speed ×3'); check('speed ×3', (await run('Admin.speed')) === 3);
  await click('Infinite stamina'); await run('Player.stamina = 0.1'); check('infinite stamina', await until('Player.stamina === 1'));
  await click('God mode');
  await click('Wake up'); await until("Joury.state === 'hunt'");
  await click('Put him in front of me');
  await run("Joury.pos.set(Player.pos.x, Joury.pos.y, Player.pos.z - 0.5)");
  await A.page.waitForTimeout(1500);
  check('god mode: Joury cannot catch you', (await run('Game.state')) === 'play');
  await click('Stun 20 s'); check('stun Joury', await until("Joury.state === 'stunned'"));
  await click('Freeze (sleep)'); check('freeze Joury', await until("Joury.state === 'dormant'"));
  await click('Free 1 kid'); check('free one kid', await until('Game.savedCount() === 1'));
  await click('Free all kids'); check('free all kids → boat phase', await until("Game.savedCount() === 10 && Game.phase === 'boat'", 10000));
  await click('Next boat part'); check('teleport to a boat part', await until('Math.min(...World.parts.map((p) => Math.hypot(p.x - Player.pos.x, p.z - Player.pos.z))) < 6'));
  await click('Put all parts on the boat'); check('all parts on the boat', await until('World.partsDelivered.size === 4'));
  await click('Show the code'); check('cabin buttons explain you are not in the cabin', (await A.page.textContent('#adminMsg')).includes("aren't in the cabin"));
  await click('God mode'); await A.page.keyboard.press('Escape');
  check('Esc closes the panel', !(await run('Admin.open')));
  await run('EFJ.catchNow()'); await until("Game.state === 'cabin'", 40000); await run('EFJ.skipWake()');
  await A.page.keyboard.press('F8'); await A.page.waitForTimeout(300);
  await click('Show the code'); const code = await run("Cabin.digits.join(' ')");
  check('shows the cabin code', (await A.page.textContent('#adminMsg')).includes(code), code);
  await click('Find all 4 digits'); check('finds all 4 digits', await run('Cabin.found.every(Boolean)'));
  const t0 = await run('Cabin.timer'); await click('+60 seconds'); check('+60 seconds', (await run('Cabin.timer')) > t0 + 50);
  await click('Escape now'); check('escape the cabin', await until("Game.state === 'play'"));
  await A.page.keyboard.press('F8'); await A.page.waitForTimeout(300); await click('Launch the boat (win)');
  check('launch the boat → ending', await until("Game.state === 'ending'"));

  // online: a player who joins can use their own tools but not the island
  await A.browser.close();
  const H = await open(), C = await open();
  const runH = (c) => H.page.evaluate((x) => EFJ.run(x), c), runC = (c) => C.page.evaluate((x) => EFJ.run(x), c);
  await runC("Perks.redeem('ADMIN')");
  await H.page.click('#btnTogether'); await H.page.click('#btnHost'); await H.page.waitForFunction(() => EFJ.run('Net.peer && Net.peer.open'));
  const room = await runH('Net.code');
  await C.page.click('#btnTogether'); await C.page.evaluate((c) => EFJ.run("Lobby.setCode('" + c + "')"), room); await C.page.click('#btnJoin');
  await C.page.waitForFunction(() => EFJ.run('Net.joined && Net.players.size === 2'));
  await H.page.click('#btnStartMp'); await C.page.waitForFunction(() => EFJ.state === 'play');
  await C.page.keyboard.press('F8'); await C.page.waitForTimeout(400);
  check('online non-host: island buttons are disabled', await C.page.isDisabled('#adminBody .adm-btn:text-is("Free all kids")'));
  check('online non-host: own tools still work', !(await C.page.isDisabled('#adminBody .adm-btn:text-is("God mode")')));
  await C.page.click('#adminBody .adm-btn:text-is("Dock & boat")');
  check('online non-host: teleport works and others see it', await H.page.waitForFunction(() => EFJ.run("(() => { const p = Net.players.get('p1'); return p && World.onDock(p.x, p.z); })()"), null, { timeout: 15000 }).then(() => true).catch(() => false));
  console.log(results.join('\n')); console.log('--- errors ---\n' + [A.logs, H.logs, C.logs].map((l) => l.join('\n')).join('\n'));
  process.exit(fails ? 1 : 0);
})().catch((e) => { console.log(results.join('\n')); console.error('CRASH', e.message); process.exit(1); });
